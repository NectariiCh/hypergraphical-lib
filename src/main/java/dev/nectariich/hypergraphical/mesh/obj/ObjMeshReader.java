package dev.nectariich.hypergraphical.mesh.obj;

import dev.nectariich.hypergraphical.Hypergraphical;
import dev.nectariich.hypergraphical.mesh.MeshData;
import it.unimi.dsi.fastutil.floats.FloatArrayList;
import it.unimi.dsi.fastutil.ints.IntArrayList;
import it.unimi.dsi.fastutil.longs.Long2IntOpenHashMap;
import net.minecraft.resources.ResourceLocation;

import javax.annotation.Nullable;
import java.io.IOException;
import java.io.InputStream;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;

/**
 * Imports a Wavefront {@code .obj} into a {@link MeshData} ready for GPU upload.
 *
 * <p>Handles the whole practical subset: {@code v}/{@code vt}/{@code vn}, all four face
 * reference forms ({@code v}, {@code v/vt}, {@code v//vn}, {@code v/vt/vn}), negative
 * (relative) indices, n-gon faces, {@code usemtl} grouping, {@code mtllib}, and
 * {@code g}/{@code o} names.
 *
 * <p>Three things happen here that the vanilla pipeline cannot do for us:
 *
 * <ul>
 *   <li><b>Full-precision normals.</b> Kept as float32. If {@code vn} is absent, smooth
 *       normals are generated by area-weighted accumulation across shared positions, which
 *       is what makes an untouched Blender export look right instead of faceted.</li>
 *   <li><b>Tangent generation.</b> Derived from UV derivatives and Gram-Schmidt
 *       orthogonalised against the normal, with handedness in {@code w}. Nothing samples a
 *       normal map yet, but tangents have to be built at import time &mdash; they cannot be
 *       recovered later, and rebuilding every mesh when normal mapping lands would be a
 *       pointless migration.</li>
 *   <li><b>Vertex de-duplication.</b> Faces are welded on the {@code (v, vt, vn)} triple, so
 *       a cube exported with 36 loose corners uploads as 24 vertices and an index buffer.</li>
 * </ul>
 */
public final class ObjMeshReader {

    /** Mesh plus the material library it referenced, so callers can derive auto-materials. */
    public record Result(MeshData mesh, MtlLibrary materials, List<String> subMeshNames) {}

    private ObjMeshReader() {}

    /**
     * @param objLocation logical location of the OBJ, used to resolve {@code mtllib} paths
     * @param mtlResolver opens a referenced {@code .mtl}, or returns {@code null} if absent
     */
    public static Result read(InputStream in,
                              ResourceLocation objLocation,
                              ObjImportSettings settings,
                              MtlResolver mtlResolver) throws IOException {
        return new Parser(objLocation, settings, mtlResolver).parse(in);
    }

    /** Opens the stream for a referenced {@code .mtl}, or {@code null} when it is missing. */
    public interface MtlResolver {
        @Nullable
        InputStream open(ResourceLocation mtl) throws IOException;
    }

    /**
     * Deterministic material id for a {@code usemtl} name inside a given OBJ, used when
     * {@code auto_materials} is on. Sanitised to the characters a ResourceLocation path
     * allows, since {@code usemtl} names are arbitrary text.
     */
    public static ResourceLocation autoMaterialId(ResourceLocation objLocation, String mtlName) {
        String path = "auto/" + objLocation.getNamespace() + '/'
                + sanitize(objLocation.getPath()) + '/' + sanitize(mtlName);
        return Hypergraphical.id(path);
    }

    private static String sanitize(String raw) {
        StringBuilder sb = new StringBuilder(raw.length());
        for (char c : raw.toLowerCase(Locale.ROOT).toCharArray()) {
            sb.append((c >= 'a' && c <= 'z') || (c >= '0' && c <= '9')
                    || c == '_' || c == '.' || c == '-' || c == '/' ? c : '_');
        }
        return sb.toString();
    }

    // =========================================================================

    private static final class Parser {

        private final ResourceLocation objLocation;
        private final ObjImportSettings settings;
        private final MtlResolver mtlResolver;

        private final FloatArrayList positions = new FloatArrayList();
        private final FloatArrayList uvs = new FloatArrayList();
        private final FloatArrayList normals = new FloatArrayList();

        /** Output vertices, interleaved in {@link MeshData}'s layout. */
        private final FloatArrayList out = new FloatArrayList();

        /** Source position index per output vertex, needed for smooth normal accumulation. */
        private final IntArrayList outPositionIndex = new IntArrayList();

        /** (v,vt,vn) triple -> output vertex index. */
        private final Long2IntOpenHashMap weld = new Long2IntOpenHashMap();

        /** usemtl name -> index list, in first-appearance order. */
        private final Map<String, IntArrayList> groups = new LinkedHashMap<>();

        private MtlLibrary materials = MtlLibrary.empty();
        private boolean sawNormals;
        private String currentMaterial = "default";
        private IntArrayList currentIndices;

        Parser(ResourceLocation objLocation, ObjImportSettings settings, MtlResolver mtlResolver) {
            this.objLocation = objLocation;
            this.settings = settings;
            this.mtlResolver = mtlResolver;
            this.weld.defaultReturnValue(-1);
            this.currentIndices = this.groups.computeIfAbsent("default", k -> new IntArrayList());
        }

        Result parse(InputStream in) throws IOException {
            if (this.settings.mtlOverride() != null) {
                loadMtl(this.settings.mtlOverride());
            }

            try (ObjTokenSource tokens = new ObjTokenSource(in)) {
                String[] line;
                while ((line = tokens.nextLine()) != null) {
                    switch (line[0]) {
                        case "v" -> {
                            float s = this.settings.scale();
                            this.positions.add(f(line, 1) * s);
                            this.positions.add(f(line, 2) * s);
                            this.positions.add(f(line, 3) * s);
                        }
                        case "vt" -> {
                            float u = f(line, 1);
                            float v = f(line, 2);
                            this.uvs.add(u);
                            this.uvs.add(this.settings.flipV() ? 1.0F - v : v);
                        }
                        case "vn" -> {
                            this.sawNormals = true;
                            this.normals.add(f(line, 1));
                            this.normals.add(f(line, 2));
                            this.normals.add(f(line, 3));
                        }
                        case "f" -> face(line);
                        case "usemtl" -> {
                            this.currentMaterial = line.length > 1 ? line[1] : "default";
                            this.currentIndices = this.groups.computeIfAbsent(
                                    this.currentMaterial, k -> new IntArrayList());
                        }
                        case "mtllib" -> {
                            if (this.settings.mtlOverride() == null && line.length > 1) {
                                loadMtl(MtlLibrary.resolveRelative(this.objLocation, line[1]));
                            }
                        }
                        default -> {
                            // g / o / s / vp / l / curv ... nothing we need.
                        }
                    }
                }
            }

            return finish();
        }

        private void loadMtl(ResourceLocation mtlLocation) {
            try (InputStream stream = this.mtlResolver.open(mtlLocation)) {
                if (stream == null) {
                    Hypergraphical.LOGGER.warn("[hypergraphical] {} references missing material library {}",
                            this.objLocation, mtlLocation);
                    return;
                }
                this.materials = MtlLibrary.parse(stream, mtlLocation);
            } catch (Exception e) {
                Hypergraphical.LOGGER.warn("[hypergraphical] Failed to read material library {}: {}",
                        mtlLocation, e.toString());
            }
        }

        /** Triangulates one face as a fan around its first corner. */
        private void face(String[] line) {
            int corners = line.length - 1;
            if (corners < 3) {
                return;
            }
            int first = vertex(line[1]);
            int prev = vertex(line[2]);
            for (int i = 3; i <= corners; i++) {
                int cur = vertex(line[i]);
                if (first >= 0 && prev >= 0 && cur >= 0) {
                    this.currentIndices.add(first);
                    this.currentIndices.add(prev);
                    this.currentIndices.add(cur);
                }
                prev = cur;
            }
        }

        /** Resolves one {@code v/vt/vn} corner to an output vertex index, welding duplicates. */
        private int vertex(String token) {
            int vi = -1;
            int ti = -1;
            int ni = -1;

            int slash1 = token.indexOf('/');
            if (slash1 < 0) {
                vi = resolve(token, this.positions.size() / 3);
            } else {
                vi = resolve(token.substring(0, slash1), this.positions.size() / 3);
                int slash2 = token.indexOf('/', slash1 + 1);
                if (slash2 < 0) {
                    ti = resolve(token.substring(slash1 + 1), this.uvs.size() / 2);
                } else {
                    String uvPart = token.substring(slash1 + 1, slash2);
                    if (!uvPart.isEmpty()) {
                        ti = resolve(uvPart, this.uvs.size() / 2);
                    }
                    ni = resolve(token.substring(slash2 + 1), this.normals.size() / 3);
                }
            }

            if (vi < 0 || vi * 3 + 2 >= this.positions.size()) {
                return -1;
            }
            boolean useSourceNormals = this.sawNormals
                    && this.settings.normals() == ObjImportSettings.NormalMode.AUTO;
            if (!useSourceNormals) {
                ni = -1;
            }

            // FLAT needs one output vertex per corner so each triangle can own its normal.
            if (this.settings.normals() != ObjImportSettings.NormalMode.FLAT) {
                long key = (vi & 0x1FFFFFL) | ((long) (ti + 1) & 0x1FFFFFL) << 21
                        | ((long) (ni + 1) & 0x1FFFFFL) << 42;
                int existing = this.weld.get(key);
                if (existing >= 0) {
                    return existing;
                }
                int index = emit(vi, ti, ni);
                this.weld.put(key, index);
                return index;
            }
            return emit(vi, ti, ni);
        }

        private int emit(int vi, int ti, int ni) {
            int index = this.out.size() / MeshData.STRIDE_FLOATS;

            this.out.add(this.positions.getFloat(vi * 3));
            this.out.add(this.positions.getFloat(vi * 3 + 1));
            this.out.add(this.positions.getFloat(vi * 3 + 2));

            if (ni >= 0 && ni * 3 + 2 < this.normals.size()) {
                this.out.add(this.normals.getFloat(ni * 3));
                this.out.add(this.normals.getFloat(ni * 3 + 1));
                this.out.add(this.normals.getFloat(ni * 3 + 2));
            } else {
                this.out.add(0.0F);
                this.out.add(0.0F);
                this.out.add(0.0F);
            }

            if (ti >= 0 && ti * 2 + 1 < this.uvs.size()) {
                this.out.add(this.uvs.getFloat(ti * 2));
                this.out.add(this.uvs.getFloat(ti * 2 + 1));
            } else {
                this.out.add(0.0F);
                this.out.add(0.0F);
            }

            this.out.add(0.0F);
            this.out.add(0.0F);
            this.out.add(0.0F);
            this.out.add(1.0F);

            this.outPositionIndex.add(vi);
            return index;
        }

        /** OBJ indices are 1-based; negative values are relative to the end of the list. */
        private static int resolve(String raw, int count) {
            try {
                int i = Integer.parseInt(raw.trim());
                return i < 0 ? count + i : i - 1;
            } catch (NumberFormatException e) {
                return -1;
            }
        }

        private static float f(String[] parts, int index) {
            if (index >= parts.length) {
                return 0.0F;
            }
            try {
                return Float.parseFloat(parts[index]);
            } catch (NumberFormatException e) {
                return 0.0F;
            }
        }

        private Result finish() {
            float[] vertices = this.out.toFloatArray();
            int vertexCount = vertices.length / MeshData.STRIDE_FLOATS;

            // Concatenate groups so every sub-mesh is a contiguous index range.
            int total = 0;
            for (IntArrayList list : this.groups.values()) {
                total += list.size();
            }
            int[] indices = new int[total];
            List<MeshData.SubMesh> subMeshes = new ArrayList<>();
            List<String> names = new ArrayList<>();
            int cursor = 0;
            for (Map.Entry<String, IntArrayList> entry : this.groups.entrySet()) {
                IntArrayList list = entry.getValue();
                if (list.isEmpty()) {
                    continue;
                }
                for (int i = 0; i < list.size(); i++) {
                    indices[cursor + i] = list.getInt(i);
                }
                ResourceLocation auto = this.settings.autoMaterials()
                        ? autoMaterialId(this.objLocation, entry.getKey())
                        : null;
                subMeshes.add(new MeshData.SubMesh(entry.getKey(), cursor, list.size(), auto));
                names.add(entry.getKey());
                cursor += list.size();
            }

            boolean needNormals = !this.sawNormals
                    || this.settings.normals() != ObjImportSettings.NormalMode.AUTO;
            if (needNormals) {
                generateNormals(vertices, indices, vertexCount);
            } else {
                normalizeNormals(vertices, vertexCount);
            }
            generateTangents(vertices, indices, vertexCount);

            float[] min = {Float.MAX_VALUE, Float.MAX_VALUE, Float.MAX_VALUE};
            float[] max = {-Float.MAX_VALUE, -Float.MAX_VALUE, -Float.MAX_VALUE};
            for (int v = 0; v < vertexCount; v++) {
                int base = v * MeshData.STRIDE_FLOATS;
                for (int axis = 0; axis < 3; axis++) {
                    float value = vertices[base + axis];
                    min[axis] = Math.min(min[axis], value);
                    max[axis] = Math.max(max[axis], value);
                }
            }
            if (vertexCount == 0) {
                min = new float[3];
                max = new float[3];
            }

            return new Result(new MeshData(vertices, indices, subMeshes, min, max),
                    this.materials, names);
        }

        private void generateNormals(float[] vertices, int[] indices, int vertexCount) {
            boolean flat = this.settings.normals() == ObjImportSettings.NormalMode.FLAT;

            // Accumulate into a per-source-position buffer so normals smooth across welded
            // vertices that differ only in UV. Accumulating per output vertex instead would
            // leave a visible crease along every UV seam.
            int positionCount = this.positions.size() / 3;
            float[] accum = new float[flat ? 0 : positionCount * 3];

            for (int t = 0; t + 2 < indices.length; t += 3) {
                int a = indices[t] * MeshData.STRIDE_FLOATS;
                int b = indices[t + 1] * MeshData.STRIDE_FLOATS;
                int c = indices[t + 2] * MeshData.STRIDE_FLOATS;

                float e1x = vertices[b] - vertices[a];
                float e1y = vertices[b + 1] - vertices[a + 1];
                float e1z = vertices[b + 2] - vertices[a + 2];
                float e2x = vertices[c] - vertices[a];
                float e2y = vertices[c + 1] - vertices[a + 1];
                float e2z = vertices[c + 2] - vertices[a + 2];

                // Unnormalised cross product: its magnitude is twice the triangle area, which
                // is exactly the area weighting we want for free.
                float nx = e1y * e2z - e1z * e2y;
                float ny = e1z * e2x - e1x * e2z;
                float nz = e1x * e2y - e1y * e2x;

                if (flat) {
                    for (int corner = 0; corner < 3; corner++) {
                        int base = indices[t + corner] * MeshData.STRIDE_FLOATS;
                        vertices[base + MeshData.OFF_NORMAL] = nx;
                        vertices[base + MeshData.OFF_NORMAL + 1] = ny;
                        vertices[base + MeshData.OFF_NORMAL + 2] = nz;
                    }
                } else {
                    for (int corner = 0; corner < 3; corner++) {
                        int p = this.outPositionIndex.getInt(indices[t + corner]) * 3;
                        accum[p] += nx;
                        accum[p + 1] += ny;
                        accum[p + 2] += nz;
                    }
                }
            }

            if (!flat) {
                for (int v = 0; v < vertexCount; v++) {
                    int p = this.outPositionIndex.getInt(v) * 3;
                    int base = v * MeshData.STRIDE_FLOATS + MeshData.OFF_NORMAL;
                    vertices[base] = accum[p];
                    vertices[base + 1] = accum[p + 1];
                    vertices[base + 2] = accum[p + 2];
                }
            }
            normalizeNormals(vertices, vertexCount);
        }

        private static void normalizeNormals(float[] vertices, int vertexCount) {
            for (int v = 0; v < vertexCount; v++) {
                int base = v * MeshData.STRIDE_FLOATS + MeshData.OFF_NORMAL;
                float x = vertices[base];
                float y = vertices[base + 1];
                float z = vertices[base + 2];
                float len = (float) Math.sqrt(x * x + y * y + z * z);
                if (len > 1.0E-8F) {
                    vertices[base] = x / len;
                    vertices[base + 1] = y / len;
                    vertices[base + 2] = z / len;
                } else {
                    vertices[base] = 0.0F;
                    vertices[base + 1] = 1.0F;
                    vertices[base + 2] = 0.0F;
                }
            }
        }

        /**
         * Per-vertex tangent frame from UV derivatives, accumulated over adjacent triangles
         * and then orthogonalised against the normal. {@code w} carries handedness so the
         * bitangent is {@code cross(N, T) * w} and does not need its own attribute.
         */
        private static void generateTangents(float[] vertices, int[] indices, int vertexCount) {
            float[] tan = new float[vertexCount * 3];
            float[] bitan = new float[vertexCount * 3];

            for (int t = 0; t + 2 < indices.length; t += 3) {
                int ia = indices[t];
                int ib = indices[t + 1];
                int ic = indices[t + 2];
                int a = ia * MeshData.STRIDE_FLOATS;
                int b = ib * MeshData.STRIDE_FLOATS;
                int c = ic * MeshData.STRIDE_FLOATS;

                float e1x = vertices[b] - vertices[a];
                float e1y = vertices[b + 1] - vertices[a + 1];
                float e1z = vertices[b + 2] - vertices[a + 2];
                float e2x = vertices[c] - vertices[a];
                float e2y = vertices[c + 1] - vertices[a + 1];
                float e2z = vertices[c + 2] - vertices[a + 2];

                float du1 = vertices[b + MeshData.OFF_UV] - vertices[a + MeshData.OFF_UV];
                float dv1 = vertices[b + MeshData.OFF_UV + 1] - vertices[a + MeshData.OFF_UV + 1];
                float du2 = vertices[c + MeshData.OFF_UV] - vertices[a + MeshData.OFF_UV];
                float dv2 = vertices[c + MeshData.OFF_UV + 1] - vertices[a + MeshData.OFF_UV + 1];

                float det = du1 * dv2 - du2 * dv1;
                if (Math.abs(det) < 1.0E-12F) {
                    continue; // Degenerate or missing UVs; leave for the fallback below.
                }
                float r = 1.0F / det;

                float tx = (e1x * dv2 - e2x * dv1) * r;
                float ty = (e1y * dv2 - e2y * dv1) * r;
                float tz = (e1z * dv2 - e2z * dv1) * r;
                float bx = (e2x * du1 - e1x * du2) * r;
                float by = (e2y * du1 - e1y * du2) * r;
                float bz = (e2z * du1 - e1z * du2) * r;

                for (int index : new int[] {ia, ib, ic}) {
                    tan[index * 3] += tx;
                    tan[index * 3 + 1] += ty;
                    tan[index * 3 + 2] += tz;
                    bitan[index * 3] += bx;
                    bitan[index * 3 + 1] += by;
                    bitan[index * 3 + 2] += bz;
                }
            }

            for (int v = 0; v < vertexCount; v++) {
                int base = v * MeshData.STRIDE_FLOATS;
                float nx = vertices[base + MeshData.OFF_NORMAL];
                float ny = vertices[base + MeshData.OFF_NORMAL + 1];
                float nz = vertices[base + MeshData.OFF_NORMAL + 2];

                float tx = tan[v * 3];
                float ty = tan[v * 3 + 1];
                float tz = tan[v * 3 + 2];

                // Gram-Schmidt: T -= N * dot(N, T)
                float d = nx * tx + ny * ty + nz * tz;
                tx -= nx * d;
                ty -= ny * d;
                tz -= nz * d;

                float len = (float) Math.sqrt(tx * tx + ty * ty + tz * tz);
                if (len < 1.0E-8F) {
                    // No usable UV derivative. Any tangent orthogonal to N will do; picking
                    // the axis least aligned with N keeps the cross product well conditioned.
                    float ax = Math.abs(nx) < 0.9F ? 1.0F : 0.0F;
                    float ay = Math.abs(nx) < 0.9F ? 0.0F : 1.0F;
                    tx = ny * 0.0F - nz * ay;
                    ty = nz * ax - nx * 0.0F;
                    tz = nx * ay - ny * ax;
                    len = (float) Math.sqrt(tx * tx + ty * ty + tz * tz);
                    if (len < 1.0E-8F) {
                        tx = 1.0F;
                        ty = 0.0F;
                        tz = 0.0F;
                        len = 1.0F;
                    }
                }
                tx /= len;
                ty /= len;
                tz /= len;

                // Handedness: sign of dot(cross(N, T), B)
                float cx = ny * tz - nz * ty;
                float cy = nz * tx - nx * tz;
                float cz = nx * ty - ny * tx;
                float handed = cx * bitan[v * 3] + cy * bitan[v * 3 + 1] + cz * bitan[v * 3 + 2];

                vertices[base + MeshData.OFF_TANGENT] = tx;
                vertices[base + MeshData.OFF_TANGENT + 1] = ty;
                vertices[base + MeshData.OFF_TANGENT + 2] = tz;
                vertices[base + MeshData.OFF_TANGENT + 3] = handed < 0.0F ? -1.0F : 1.0F;
            }
        }
    }
}
